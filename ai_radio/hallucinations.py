"""Отсев галлюцинаций STT — того, что Whisper «слышит» в шуме и тишине.

Whisper обучен на субтитрах, и на сигнале без речи договаривает то, чем субтитры
заканчиваются: «Продолжение следует», «Редактор субтитров А.Семкин», «Субтитры
создавал DimaTorzok». В журнале дачной машины за первые сутки таких фраз 1224 из
1852 — и агент ответил на 330 из них, потому что окно диалога после позывного
открыто, а галлюцинация приходит как обычная реплика.

**Метрики самого Whisper здесь не помогают.** Замер на реальном шуме с прода
(беспроводной микрофон, 180 с, порог 0.00243):

    no_speech_prob = 0.000   avg_logprob = -0.276   compression_ratio = 0.83

То есть модель уверена в том, что галлюцинирует: пороги `no_speech_threshold`
(0.6) и `log_prob_threshold` (-1.0) не срабатывают, и поднимать их нельзя — под нож
пойдёт живая речь с рации, которая и так на пределе разборчивости. Отсюда фильтр по
тексту и по длительности, а не по уверенности модели.

Каждое правило проверено на 1852 фразах из журнала: см. `verdict` — там же цена
каждого в ложных срабатываниях.
"""
from __future__ import annotations

import re
from typing import Optional

# Хвосты и шапки субтитров. Ловят 1024 фразы из 1852 в журнале прода — это главный
# фильтр; остальные правила добирают то, чего в списке ещё нет.
SUBTITLE_MARKERS = re.compile(
    r"продолжение\s+следует"
    r"|продолжение\s+в\s+следующей\s+части"
    r"|субтитр"                      # «Субтитры сделал/создавал/подогнал…»
    r"|редактор\s+субтитров"
    r"|корректор\s+[А-ЯЁ]"
    r"|спасибо\s+за\s+(просмотр|внимание)"
    r"|подписывайтесь\s+на\s+канал"
    r"|ставьте\s+лайк"
    r"|dimatorzok|дима\s*торзок|терзок"
    r"|amara\.org|напишите\s+в\s+комментариях",
    re.IGNORECASE)

# Фразы-одиночки, которыми Whisper размечает неречевой звук. Только целиком:
# «музыка» внутри живой реплики — обычное слово.
STANDALONE_TAGS = {
    "музыка", "аплодисменты", "смех", "звонок", "гудок", "тишина",
    "играет музыка", "звук", "шум", "кашель",
}


def _norm(text: str) -> str:
    return re.sub(r"[^а-яёa-z ]", " ", text.lower()).strip()


def verdict(text: str, duration_s: Optional[float] = None,
            initial_prompt: str = "", min_chars_per_s: float = 0.0,
            max_chars_per_s: float = 30.0, long_dur_s: float = 8.0,
            long_min_chars: int = 25) -> Optional[str]:
    """Вернуть причину, по которой текст считается галлюцинацией, или None.

    Пороги — из замеров на журнале прода; в скобках цена правила на тех же данных.
    """
    stripped = text.strip()
    if not stripped:
        return "пусто"

    if SUBTITLE_MARKERS.search(stripped):        # 1024 попадания, ложных нет
        return "субтитры"

    if _norm(stripped) in STANDALONE_TAGS:       # «Музыка.», «Аплодисменты.»
        return "разметка неречевого звука"

    # Эхо initial_prompt: Whisper пересказывает подсказку, которую мы же ему дали
    # (23 попадания: «Радиосвязь.», «Позывной Феечка.»). Сравниваем по предложениям
    # целиком, чтобы живая реплика с теми же словами не пострадала.
    if initial_prompt:
        parts = {_norm(p) for p in re.split(r"[.!?]+", initial_prompt) if _norm(p)}
        if _norm(stripped) in parts:
            return "эхо подсказки STT"

    if duration_s and duration_s > 0:
        rate = len(stripped) / duration_s
        # Быстрее 30 симв/с человек не говорит: это «Ту-ту-ту-ту…» и «Уууу…» (3)
        if rate > max_chars_per_s:
            return f"{rate:.0f} симв/с — так не говорят"
        if min_chars_per_s and rate < min_chars_per_s:
            return f"{rate:.1f} симв/с — подозрительно медленно"
        # Длинная передача, а текста на пару слов — обычно шум, из которого Whisper
        # выжал одну фразу (47 попаданий, из них 43 субтитры; ложных 4 из 1852)
        if duration_s > long_dur_s and len(stripped) < long_min_chars:
            return f"{duration_s:.0f} с эфира на {len(stripped)} символов"

    return None
